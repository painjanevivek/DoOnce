import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(repositoryRoot, "contracts", "protocol.v1.schema.json");
const outputPath = path.join(repositoryRoot, "contracts", "protocol.v1.validators.ts");
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const contractNames = [
  "WorkflowSpec",
  "CaptureSessionSummary",
  "WorkflowCompilation",
];

const ajv = new Ajv2020({
  allErrors: true,
  code: { esm: true, source: true },
  strict: true,
  validateFormats: true,
});
addFormats(ajv);
ajv.addSchema(schema, schema.$id);

const references = Object.fromEntries(
  contractNames.map((name) => {
    const reference = `${schema.$id}#/$defs/${name}`;
    assert.ok(ajv.getSchema(reference), `Unable to compile ${name}.`);
    return [name, reference];
  }),
);
const source = [
  "/* eslint-disable */",
  "// @ts-nocheck -- generated by scripts/generate-contract-validators.mjs",
  standaloneCode(ajv, references),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  assert.equal(
    fs.readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n"),
    source,
    "Generated contract validators are stale. Run npm run contracts:generate.",
  );
  process.stdout.write("Generated contract validators match the protocol schema.\n");
} else {
  fs.writeFileSync(outputPath, source, "utf8");
  process.stdout.write(`Generated ${contractNames.length} standalone validators.\n`);
}
